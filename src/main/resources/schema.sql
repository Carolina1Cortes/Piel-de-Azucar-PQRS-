-- =====================================================================
-- APOLO - Esquema relacional (H2 embebido, modo archivo)
-- Versionado en el repositorio. Se ejecuta en cada arranque, por eso
-- todo usa IF NOT EXISTS. Las enumeraciones son VARCHAR con CHECK.
-- Los identificadores generados empiezan en 1000: los ids 1..999 quedan
-- reservados para los datos de prueba (data.sql).
-- =====================================================================

CREATE TABLE IF NOT EXISTS cliente (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    nombre    VARCHAR(150) NOT NULL,
    correo    VARCHAR(255) NOT NULL,
    telefono  VARCHAR(30),
    CONSTRAINT uq_cliente_correo UNIQUE (correo)
);

CREATE TABLE IF NOT EXISTS usuario (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    nombre           VARCHAR(150) NOT NULL,
    correo           VARCHAR(255) NOT NULL,
    contrasena_hash  VARCHAR(100) NOT NULL,
    rol              VARCHAR(30)  NOT NULL,
    bloqueado        BOOLEAN DEFAULT FALSE NOT NULL,
    CONSTRAINT uq_usuario_correo UNIQUE (correo),
    CONSTRAINT ck_usuario_rol CHECK (rol IN ('OPERADOR', 'ADMIN'))
);

CREATE TABLE IF NOT EXISTS tipo_consulta (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    descripcion           VARCHAR(200) NOT NULL,
    categoria             VARCHAR(40)  NOT NULL,
    prioridad_por_defecto VARCHAR(30)  NOT NULL,
    automatizacion        VARCHAR(30)  NOT NULL,
    CONSTRAINT ck_tipo_categoria CHECK (categoria IN ('PEDIDOS', 'ENVIOS_ENTREGAS', 'PRODUCTOS_USO', 'REACCIONES',
        'CAMBIOS_DEVOLUCIONES', 'PAGOS_FACTURACION', 'ATENCION_QUEJAS', 'SUGERENCIAS_FELICITACIONES')),
    CONSTRAINT ck_tipo_prioridad CHECK (prioridad_por_defecto IN ('BAJA', 'MEDIA', 'ALTA', 'CRITICA')),
    CONSTRAINT ck_tipo_automatizacion CHECK (automatizacion IN ('AUTOMATICA', 'ASISTIDA', 'ATENCION_HUMANA', 'REGISTRO'))
);

CREATE TABLE IF NOT EXISTS plantilla_respuesta (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    nombre           VARCHAR(150)  NOT NULL,
    asunto           VARCHAR(200)  NOT NULL,
    cuerpo           VARCHAR(4000) NOT NULL,
    palabras_clave   VARCHAR(500),
    tipo_consulta_id BIGINT,
    activa           BOOLEAN DEFAULT TRUE NOT NULL,
    CONSTRAINT fk_plantilla_tipo FOREIGN KEY (tipo_consulta_id) REFERENCES tipo_consulta (id)
);

CREATE TABLE IF NOT EXISTS pqrs (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    id_externo           VARCHAR(255),
    canal                VARCHAR(30)  NOT NULL,
    fecha_llegada        TIMESTAMP    NOT NULL,
    asunto               VARCHAR(300) NOT NULL,
    estado               VARCHAR(30)  NOT NULL,
    prioridad            VARCHAR(30)  NOT NULL,
    fecha_limite         DATE         NOT NULL,
    descripcion_solucion VARCHAR(2000),
    fecha_resolucion     TIMESTAMP,
    cliente_id           BIGINT NOT NULL,
    tipo_consulta_id     BIGINT NOT NULL,
    responsable_id       BIGINT,
    resuelta_por_id      BIGINT,
    CONSTRAINT uq_pqrs_id_externo UNIQUE (id_externo),
    CONSTRAINT ck_pqrs_canal CHECK (canal IN ('GMAIL')),
    CONSTRAINT ck_pqrs_estado CHECK (estado IN ('PENDIENTE', 'EN_ATENCION', 'ESCALADA', 'DELEGADA', 'RESUELTA')),
    CONSTRAINT ck_pqrs_prioridad CHECK (prioridad IN ('BAJA', 'MEDIA', 'ALTA', 'CRITICA')),
    CONSTRAINT fk_pqrs_cliente FOREIGN KEY (cliente_id) REFERENCES cliente (id),
    CONSTRAINT fk_pqrs_tipo FOREIGN KEY (tipo_consulta_id) REFERENCES tipo_consulta (id),
    CONSTRAINT fk_pqrs_responsable FOREIGN KEY (responsable_id) REFERENCES usuario (id),
    CONSTRAINT fk_pqrs_resuelta_por FOREIGN KEY (resuelta_por_id) REFERENCES usuario (id)
);
CREATE INDEX IF NOT EXISTS ix_pqrs_estado ON pqrs (estado);
CREATE INDEX IF NOT EXISTS ix_pqrs_prioridad ON pqrs (prioridad);
CREATE INDEX IF NOT EXISTS ix_pqrs_fecha_limite ON pqrs (fecha_limite);

CREATE TABLE IF NOT EXISTS mensaje (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    pqrs_id    BIGINT        NOT NULL,
    fecha      TIMESTAMP     NOT NULL,
    asunto     VARCHAR(300),
    cuerpo     VARCHAR(4000) NOT NULL,
    direccion  VARCHAR(30)   NOT NULL,
    automatico BOOLEAN DEFAULT FALSE NOT NULL,
    autor_id   BIGINT,
    CONSTRAINT ck_mensaje_direccion CHECK (direccion IN ('ENTRANTE', 'SALIENTE')),
    CONSTRAINT fk_mensaje_pqrs FOREIGN KEY (pqrs_id) REFERENCES pqrs (id),
    CONSTRAINT fk_mensaje_autor FOREIGN KEY (autor_id) REFERENCES usuario (id)
);
CREATE INDEX IF NOT EXISTS ix_mensaje_pqrs ON mensaje (pqrs_id);

CREATE TABLE IF NOT EXISTS adjunto (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    nombre_archivo VARCHAR(255) NOT NULL,
    ruta           VARCHAR(500) NOT NULL,
    tipo_mime      VARCHAR(100),
    mensaje_id     BIGINT,
    plantilla_id   BIGINT,
    CONSTRAINT fk_adjunto_mensaje FOREIGN KEY (mensaje_id) REFERENCES mensaje (id),
    CONSTRAINT fk_adjunto_plantilla FOREIGN KEY (plantilla_id) REFERENCES plantilla_respuesta (id),
    -- Un adjunto pertenece a un mensaje o a una plantilla, nunca a ambos ni a ninguno.
    CONSTRAINT ck_adjunto_dueno CHECK ((mensaje_id IS NOT NULL AND plantilla_id IS NULL)
                                    OR (mensaje_id IS NULL AND plantilla_id IS NOT NULL))
);

CREATE TABLE IF NOT EXISTS registro_bitacora (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    fecha          TIMESTAMP   NOT NULL,
    accion         VARCHAR(40) NOT NULL,
    motivo         VARCHAR(1000),
    notas_internas VARCHAR(2000),
    pqrs_id        BIGINT,
    usuario_id     BIGINT,   -- NULL cuando la acción la hizo el sistema
    CONSTRAINT ck_bitacora_accion CHECK (accion IN ('CASO_TOMADO', 'RESPUESTA_ENVIADA', 'ESCALADA', 'DELEGADA',
        'PRIORIDAD_CAMBIADA', 'OPERADOR_BLOQUEADO', 'CASO_RESUELTO')),
    CONSTRAINT fk_bitacora_pqrs FOREIGN KEY (pqrs_id) REFERENCES pqrs (id),
    CONSTRAINT fk_bitacora_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id)
);
CREATE INDEX IF NOT EXISTS ix_bitacora_pqrs ON registro_bitacora (pqrs_id);

CREATE TABLE IF NOT EXISTS festivo (
    fecha  DATE PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL
);
